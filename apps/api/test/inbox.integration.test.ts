import assert from 'node:assert/strict';
import { createHash, randomBytes, randomUUID } from 'node:crypto';
import { test } from 'node:test';
import pg from 'pg';
import { buildApp } from '../src/app.js';

test('la bandeja filtra y pagina sin exponer conversaciones de otra organización', async (t) => {
  const pool = new pg.Pool({ connectionTimeoutMillis: 3000 });
  const app = buildApp(pool);
  const org = randomUUID(), other = randomUUID(), user = randomUUID(), channel = randomUUID(), contact = randomUUID(), conversation = randomUUID();
  const token = randomBytes(32).toString('hex');
  t.after(async () => {
    await pool.query('DELETE FROM messages WHERE organization_id = ANY($1::uuid[])', [[org, other]]);
    await pool.query('DELETE FROM conversations WHERE organization_id = ANY($1::uuid[])', [[org, other]]);
    await pool.query('DELETE FROM contacts WHERE organization_id = ANY($1::uuid[])', [[org, other]]);
    await pool.query('DELETE FROM channel_accounts WHERE organization_id = ANY($1::uuid[])', [[org, other]]);
    await pool.query('DELETE FROM users WHERE organization_id = ANY($1::uuid[])', [[org, other]]);
    await pool.query('DELETE FROM organizations WHERE id = ANY($1::uuid[])', [[org, other]]);
    await app.close();
  });
  await pool.query('INSERT INTO organizations (id,name,slug) VALUES ($1,$1::uuid::text,$1::uuid::text),($2,$2::uuid::text,$2::uuid::text)', [org, other]);
  await pool.query("INSERT INTO users (id,organization_id,email,display_name,role) VALUES ($1,$2,$3,'Operadora','operator')", [user, org, `${user}@example.test`]);
  await pool.query("INSERT INTO auth_sessions (token_hash,user_id,expires_at,mfa_verified) VALUES ($1,$2,now()+interval '1 hour',false)", [createHash('sha256').update(token).digest('hex'), user]);
  await pool.query("INSERT INTO channel_accounts (id,organization_id,display_name,phone_number) VALUES ($1,$2,'Línea A','+5491100012345')", [channel, org]);
  await pool.query("INSERT INTO contacts (id,organization_id,display_name) VALUES ($1,$2,'Cliente prueba')", [contact, org]);
  await pool.query("INSERT INTO conversations (id,organization_id,channel_account_id,contact_id,external_id,assigned_user_id,last_message_at) VALUES ($1,$2,$3,$4,'cliente@s.whatsapp.net',$5,now())", [conversation, org, channel, contact, user]);
  await pool.query("INSERT INTO conversations (organization_id,channel_account_id,kind,external_id,last_message_at) VALUES ($1,$2,'group','grupo@g.us',now()-interval '1 minute')", [org, channel]);
  const foreignChannel = randomUUID();
  await pool.query("INSERT INTO channel_accounts (id,organization_id,display_name,phone_number) VALUES ($1,$2,'Otra organización','+5491100099999')", [foreignChannel, other]);
  await pool.query("INSERT INTO conversations (organization_id,channel_account_id,kind,external_id,last_message_at) VALUES ($1,$2,'group','privado@g.us',now())", [other, foreignChannel]);
  await pool.query("INSERT INTO messages (organization_id,channel_account_id,conversation_id,provider_message_id,direction,body,occurred_at) VALUES ($1,$2,$3,'test-1','incoming','Último mensaje',now())", [org, channel, conversation]);
  const headers = { authorization: `Bearer ${token}` };
  const response = await app.inject({ method: 'GET', url: `/api/conversations?search=cliente&channel=${channel}&status=open&operator=${user}&limit=1`, headers });
  assert.equal(response.statusCode, 200);
  const result = response.json();
  assert.equal(result.conversations.length, 1);
  assert.equal(result.conversations[0].contact_name, 'Cliente prueba');
  assert.equal(result.conversations[0].last_message, 'Último mensaje');
  assert.equal(result.conversations[0].channel_name, 'Línea A');
  assert.equal(result.hasMore, false);
  const firstPage = (await app.inject({ method: 'GET', url: '/api/conversations?limit=1', headers })).json();
  assert.equal(firstPage.hasMore, true);
  assert.equal(firstPage.conversations[0].id, conversation);
  const secondPage = (await app.inject({ method: 'GET', url: '/api/conversations?limit=1&offset=1', headers })).json();
  assert.equal(secondPage.conversations[0].kind, 'group');
  assert.equal(secondPage.hasMore, false);
  assert.equal((await app.inject({ method: 'GET', url: `/api/conversations?channel=${foreignChannel}`, headers })).json().conversations.length, 0);
  assert.equal((await app.inject({ method: 'GET', url: '/api/conversations?operator=unassigned', headers })).json().conversations.length, 1);
  assert.equal((await app.inject({ method: 'GET', url: '/api/conversations?status=resolved', headers })).json().conversations.length, 0);
  assert.equal((await app.inject({ method: 'GET', url: '/api/conversations?limit=0', headers })).statusCode, 400);
  const options = await app.inject({ method: 'GET', url: '/api/inbox/options', headers });
  assert.equal(options.statusCode, 200);
  assert.equal(options.json().channels.length, 1);
  assert.equal(options.json().channels[0].id, channel);
  assert.equal(options.json().operators[0].id, user);
});
